"""Generate hermes/, clawhub/ and the Gemini CLI commands/*.toml from the canonical files. Never edit the outputs.

    python3 build/variants.py

Hermes and ClawHub get the canonical SKILL.md body under their own frontmatter (only the sign-up link's
utm_source changes, to the catalog's name), plus byte-identical copies of the skill's scripts/ and references/.
The ClawHub frontmatter declares every env var the script reads, as ClawHub's scan compares the two. Gemini CLI gets a .toml copy of each command next to its
.md source, because Gemini loads extension commands only from the root commands/ folder.
"""
import glob
import json
import os
import re
import shutil

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BANNER = "# Generated by build/variants.py from %s. Edit the source, then rerun it."
SIGN_UP = "https://www.searchapi.io/users/sign_up?utm_source=%s&utm_medium=agent-skill&utm_campaign=searchapi-skill"

VARIANTS = {   # per skill: the short descriptions the two catalogs can show
    "searchapi": {
        "hermes": "SearchApi live search data: Google, Maps, News, AI, ads",
        "clawhub": "SearchApi live search results as data: Google, Bing, Maps, Shopping, Flights, Hotels, News, "
                   "YouTube, AI answers, ads. Use for rankings, prices, local and news.",
        "tags": ["search", "serp", "google", "web-search", "searchapi"],
    },
    "searchapi-migrate": {
        "hermes": "SearchApi migration from SerpApi, Serper, DataForSEO",
        "clawhub": "SearchApi migration: move code from SerpApi, Serper, DataForSEO or Bright Data SERP API "
                   "to SearchApi.io, with a side-by-side check.",
        "tags": ["search", "serp", "migration", "serpapi", "searchapi"],
    },
}


def split(path):
    with open(path, encoding="utf-8") as f:
        text = f.read()
    m = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    return m.group(1), text[m.end():]


def field(fm, key):
    return re.search(r'(?m)^  %s: "([^"]*)"$' % key, fm).group(1)


def hermes(name, fm, v):
    return "\n".join([
        "---",
        BANNER % ("skills/%s/SKILL.md" % name),
        "name: %s" % name,
        'description: "%s"' % v["hermes"],
        "version: %s" % field(fm, "version"),
        "author: SearchApi",
        "license: MIT",
        "required_environment_variables:",
        "  - name: SEARCHAPI_API_KEY",
        '    prompt: "SearchApi API key"',
        '    help: "Get one at %s"' % (SIGN_UP % "hermes"),
        '    required_for: "the script path (the SearchApi MCP server signs in without a key)"',
        "metadata:",
        "  hermes:",
        "    tags: [%s]" % ", ".join(v["tags"]),
        "---",
    ]) + "\n"


def script_env():
    """Env vars the script reads, so ClawHub's scan finds each one declared: (name, why) after the key itself."""
    with open(os.path.join(ROOT, "skills", "searchapi", "scripts", "searchapi.py"), encoding="utf-8") as f:
        src = f.read()
    read = set(re.findall(r'os\.environ\.get\(\s*"([A-Z][A-Z0-9_]*)"', src))
    block = re.search(r"(?ms)^HARNESSES = (.*?)\)\)$", src).group(1)
    harness = re.findall(r'\("([A-Z][A-Z0-9_]*)", "[a-z0-9-]+"', block)
    why = {"SEARCHAPI_DIR": "Optional folder for raw responses (default: the system temp folder).",
           "SEARCHAPI_BASE_URL": "Test hook only: a localhost mock URL. Any other host is refused."}
    tag = set(harness) | {"AI_AGENT", "AGENT"}
    out = [(n, why.get(n, "Optional setting read by the script.")) for n in sorted(read - tag - {"SEARCHAPI_API_KEY"})]
    return out + [(n, "Read only to name the agent in the X-SearchApi-Client header.") for n in sorted(tag)]


def clawhub(name, fm, v):
    extra = []
    for env, why in script_env():
        extra += ["      - name: %s" % env, "        required: false", '        description: "%s"' % why]
    return "\n".join([
        "---",
        BANNER % ("skills/%s/SKILL.md" % name),
        "name: %s" % name,
        'description: "%s"' % v["clawhub"],
        "license: MIT-0",
        "metadata:",
        '  version: "%s"' % field(fm, "version"),
        '  verified_on: "%s"' % field(fm, "verified_on"),
        "  openclaw:",
        "    primaryEnv: SEARCHAPI_API_KEY",
        "    envVars:",
        "      - name: SEARCHAPI_API_KEY",
        "        required: false",
        '        description: "SearchApi API key for the script path. The SearchApi MCP server needs none. Key: %s"'
        % (SIGN_UP % "clawhub"),
    ] + extra + [
        "    requires:",
        "      anyBins: [python3]",
        "    homepage: https://www.searchapi.io",
        "---",
    ]) + "\n"


def skills():
    for name in sorted(os.listdir(os.path.join(ROOT, "skills"))):
        src = os.path.join(ROOT, "skills", name)
        if not os.path.isfile(os.path.join(src, "SKILL.md")):
            continue
        fm, body = split(os.path.join(src, "SKILL.md"))
        for harness, make in (("hermes", hermes), ("clawhub", clawhub)):
            out = os.path.join(ROOT, harness, name)
            shutil.rmtree(out, ignore_errors=True)
            for f in glob.glob(os.path.join(src, "**", "*"), recursive=True):
                rel = os.path.relpath(f, src)
                if os.path.isfile(f) and rel != "SKILL.md" and rel.split(os.sep)[0] in ("scripts", "references") \
                        and "__pycache__" not in rel:
                    os.makedirs(os.path.dirname(os.path.join(out, rel)), exist_ok=True)
                    shutil.copy2(f, os.path.join(out, rel))
            os.makedirs(out, exist_ok=True)
            with open(os.path.join(out, "SKILL.md"), "w", encoding="utf-8") as f:   # sign-ups credited to the catalog
                f.write(make(name, fm, VARIANTS[name]) + body.replace("utm_source=agent-skill", "utm_source=" + harness))
        print("wrote hermes/%s, clawhub/%s" % (name, name))


def toml_string(s):
    return '"""\n' + s.replace("\\", "\\\\").replace('"""', '\\"\\"\\"') + '"""'


def gemini():
    out = os.path.join(ROOT, "commands")
    for old in glob.glob(os.path.join(out, "*.toml")):
        os.remove(old)
    for path in sorted(glob.glob(os.path.join(ROOT, "commands", "*.md"))):
        fm, body = split(path)
        desc = re.search(r"(?m)^description: (.*)$", fm).group(1).strip()
        prompt = body.strip().replace("$ARGUMENTS", "{{args}}") + "\n"
        name = os.path.basename(path)[:-3]
        with open(os.path.join(out, name + ".toml"), "w", encoding="utf-8") as f:
            f.write(BANNER % ("commands/%s.md" % name) + "\n")
            f.write("description = %s\n" % json.dumps(desc))
            f.write("prompt = %s\n" % toml_string(prompt))
        print("wrote commands/%s.toml" % name)


if __name__ == "__main__":
    skills()
    gemini()
